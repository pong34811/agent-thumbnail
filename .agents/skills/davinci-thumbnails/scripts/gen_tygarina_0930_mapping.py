"""Generate projects/tygarina_0930/mapping.py from timeline-inventory.json + hooks_A..E.json (88 landscape timelines)."""
import json
import pprint
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
REP = ROOT / "reports/tygarina/2026-09-30"
inv = {(r["project"], r["i"]): r for r in json.loads((REP / "timeline-inventory.json").read_text(encoding="utf-8"))}
# 01_Emotions/*.png in the Channel Kit are PLACEHOLDERS (CHECKLIST.md), so real renders from 2026-07-01 stand in:
#   dsadadsad.png = happy/glasses (full body), 21.png = flirty bust, dsasa.png = neutral calm (full body)
REAL = {"02_smile.png": "dsadadsad.png", "03_shock.png": "dsadadsad.png", "07_panic.png": "dsadadsad.png", "05_smug.png": "21.png"}
# QC fixes (reports/tygarina/2026-09-30/qc_part_*.md): exact-line text corrections
TEXT_FIX = {"อุ้ย!": "อุ๊ย!", "เดี๋ยวๆๆ!": "เดี๋ยวๆ!", "เซงเลยอ่ะ": "เซ็งเลยอ่ะ", "น้ำลายฟูปาก!": "น้ำลายฟูมปาก!",
            "เลือดแค่กระจก": "เลือดแค่กระจิ๊ดเดียว", "ใครหยิบโกโกนอล": "สู้เสือมือเปล่า", "พูดไม่ออก!": "เอ่อ…ไม่ได้!",
            "ผวาหมด!": "ร้านนี้หลอน", "โดนลากหาย!": "เอ้า!แล้วไง", "โดนงาบแล้ว!": "เงียบจัง…"}
# name-substring -> new frame_tl (lobby/black frames replaced by real scene frames)
FRAME_FIX = {"เปิดตี้แจกความฮา": 44, "เสียงฝีเท้าปริศนา": 24}
DEFAULT = "dsasa.png"
rows = []
for g in "ABCDE":
    for h in json.loads((REP / f"hooks_{g}.json").read_text(encoding="utf-8")):
        t = inv[(h["project"], h["i"])]
        fx = lambda ls: [TEXT_FIX.get(x, x) for x in ls]  # noqa: E731
        h["hook"], h["sec"] = fx(h["hook"]), fx(h["sec"])
        if h["hook"] == ["กดครบทุกประโยค!"]:  # too wide for the Shorts safe zone on one line
            h["hook"] = ["กดครบ", "ทุกประโยค!"]
        for k, v in FRAME_FIX.items():
            if k in h["name"]:
                h["frame_tl"] = v
        rows.append(dict(
            id=len(rows) + 1, project=h["project"], name=h["name"], tl_short=h["tl_short"],
            src=t["src"].replace("\\", "/"), src_start=round(t["srcstart"] / t["fps"], 3), frame_tl=h["frame_tl"],
            emotion=h["model"], model_file=REAL.get(h["model"], DEFAULT), talk=h["talk"], hook=h["hook"], sec=h["sec"], evidence=h["evidence"], flag=h["flag"]))
out = '"""Tygarina 2026-09-30 mapping (88 timelines x 2 orientations). Generated by gen_tygarina_0930_mapping.py."""\n'
out += 'PROJECT_NAME = "tygarina-2026-09-30"\nCHARACTER_NAME = "tygarina"\n'
out += 'MODEL_DIR = "G:/My Drive/Projects/Tygarina/2026-07-01/โดน OBS เเกงอีกเเล้ว"\n\nTIMELINES = ' + pprint.pformat(rows, width=140, sort_dicts=False) + "\n"
(ROOT / "projects/tygarina_0930").mkdir(exist_ok=True)
(ROOT / "projects/tygarina_0930/mapping.py").write_text(out, encoding="utf-8")
(ROOT / "projects/tygarina_0930/__init__.py").write_text("", encoding="utf-8")
print(len(rows), "rows;", sum(1 for r in rows if r["flag"]), "flagged")
